import { chromium, webkit } from "@playwright/test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";

const evidence = process.env.AMBIENT_QA_DIR || new URL("../../data/backend/ambient-glow-20261021/", import.meta.url).pathname;
await fs.mkdir(evidence, { recursive: true });
const browser = await chromium.launch({ ...(process.env.QA_CHROMIUM_PATH ? { executablePath: process.env.QA_CHROMIUM_PATH } : {}), headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage"] });
const results = [];
const context = await browser.newContext({ viewport: { width: 1000, height: 900 }, reducedMotion: "no-preference" });
const page = await context.newPage();
const errors = [];
page.on("pageerror", error => errors.push(error.message));
page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
page.on("response", response => { if (response.status() >= 400) errors.push(`HTTP ${response.status()} ${response.url()}`); });
try {
  await page.goto("http://127.0.0.1:4187/tests/ambientGlow.browser.html", { waitUntil: "networkidle" });
  const input = page.getByRole("textbox", { name: "测试输入" });
  const layer = page.locator(".composerAmbientGlow");
  const canvas = page.locator(".composerAmbientGlowCanvas canvas");
  await input.focus();
  await page.waitForFunction(() => document.querySelector(".composerAmbientGlowCanvas")?.dataset.renderer === "paper");
  assert.equal(await layer.getAttribute("data-active"), "true");
  assert.equal(await canvas.count(), 1, "an empty focused editor starts the bounded glow renderer");
  results.push("空输入框聚焦点亮光效");
  await input.fill("中英文输入，We’re testing a quiet ambient glow.");
  await page.waitForFunction(() => document.querySelector(".composerAmbientGlowCanvas")?.dataset.renderer === "paper");
  await page.waitForTimeout(900);
  const info = await canvas.evaluate(element => ({ width: element.width, height: element.height }));
  assert.ok(info.width * info.height < 161000, "render resolution must remain capped");
  assert.equal(await layer.getAttribute("data-active"), "true");
  const heightRatio = await layer.evaluate(element => element.getBoundingClientRect().height / element.parentElement.getBoundingClientRect().height);
  assert.ok(Math.abs(heightRatio - .4) < .002, "ambient light must stay inside the bottom 40% envelope");
  await page.screenshot({ path: `${evidence}/01-dark-typing.png`, fullPage: true });
  results.push({ typing: "真实输入点亮、Paper渲染", pixels: info });
  await page.waitForTimeout(3200);
  assert.equal(await layer.getAttribute("data-active"), "true", "pausing typing must keep a nonempty draft lit");
  await input.fill("");
  assert.equal(await layer.getAttribute("data-active"), "true", "clearing a focused editor keeps the glow visible");
  await input.evaluate(element => element.blur());
  await page.waitForTimeout(1250);
  assert.equal(await layer.getAttribute("data-active"), "false");
  const frames = await page.locator(".composerAmbientGlowCanvas").getAttribute("data-drawn-frames");
  await page.waitForTimeout(250);
  assert.equal(await page.locator(".composerAmbientGlowCanvas").getAttribute("data-drawn-frames"), frames, "idle stops all recurring shader draws");
  await page.screenshot({ path: `${evidence}/02-idle.png`, fullPage: true });
  results.push("停笔与聚焦清空保持光效，空框失焦后渐出并停止绘制");
  await input.fill("持续草稿的光团应有可见移动。");
  await page.getByRole("button", { name: "预览连续输入", exact: true }).click();
  await page.waitForTimeout(1100);
  await page.screenshot({ path: `${evidence}/03-dark-comparison.png`, fullPage: true });
  const motionBefore = await page.locator(".composerAmbientGlowCanvas").evaluate(element => ({ transform: element.style.transform, phase: element.dataset.motionPhase }));
  await page.waitForTimeout(2500);
  assert.equal(await layer.getAttribute("data-active"), "true", "IME composition remains lit beyond idle timeout");
  await page.screenshot({ path: `${evidence}/04-dark-later.png`, fullPage: true });
  const motionAfter = await page.locator(".composerAmbientGlowCanvas").evaluate(element => ({ transform: element.style.transform, phase: element.dataset.motionPhase }));
  assert.notEqual(motionAfter.transform, motionBefore.transform);
  assert.ok(Number(motionAfter.phase) > Number(motionBefore.phase));
  results.push({ motionBefore, motionAfter });
  await page.getByRole("button", { name: "结束连续输入", exact: true }).click();
  await page.getByRole("button", { name: "切换白天／黑夜" }).click();
  await input.fill("白天模式下，输入时也保持文字清晰。");
  await page.waitForTimeout(900);
  await page.screenshot({ path: `${evidence}/05-light-typing.png`, fullPage: true });
  await page.getByRole("button", { name: "发送测试消息" }).click();
  assert.equal(await layer.getAttribute("data-active"), "false");
  await page.waitForTimeout(1250);
  assert.ok((await page.locator(".messages").textContent()).includes("白天模式"));
  results.push("发送后停止，消息不受光层遮挡");
  await page.getByRole("button", { name: "打开新会话首页" }).click();
  await page.waitForTimeout(1000);
  assert.equal(await layer.getAttribute("data-mode"), "welcome");
  assert.ok(Math.abs(await layer.evaluate(element => element.getBoundingClientRect().height / element.parentElement.getBoundingClientRect().height) - .4) < .002);
  assert.equal(await layer.getAttribute("data-active"), "true");
  await page.screenshot({ path: `${evidence}/09-new-conversation-welcome.png`, fullPage: true });
  await page.getByRole("button", { name: "切到已有会话" }).click();
  await page.waitForTimeout(1250);
  assert.equal(await layer.getAttribute("data-active"), "false");
  results.push("空白新会话显示欢迎光晕，切入已有会话后渐出");
  await page.getByRole("button", { name: "切换手机／桌面" }).click();
  await input.fill("桌面布局保持一致。");
  await page.waitForTimeout(900);
  await page.screenshot({ path: `${evidence}/06-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 393, height: 780 });
  await page.getByRole("button", { name: "切换手机／桌面" }).click();
  await input.fill("手机输入，圆角和按钮不被裁切。");
  await page.waitForTimeout(900);
  const bounds = await page.locator(".composer").boundingBox();
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 394);
  assert.equal(await input.evaluate(element => getComputedStyle(element).fontSize), "16px");
  await page.screenshot({ path: `${evidence}/07-mobile-light.png`, fullPage: true });
  await page.getByRole("button", { name: "切换白天／黑夜" }).click();
  await input.fill("手机深色，输入时才亮起。");
  await page.waitForTimeout(900);
  await page.screenshot({ path: `${evidence}/08-mobile-dark.png`, fullPage: true });
  results.push("393px手机与桌面布局，输入16px，发送控件均可点击");
  const shape = await page.locator(".composer").evaluate(element => ({ radius: getComputedStyle(element).borderRadius, corner: getComputedStyle(element).getPropertyValue("corner-shape"), filter: getComputedStyle(element).filter, transform: getComputedStyle(element).transform }));
  assert.equal(shape.filter, "none");
  assert.ok(shape.transform === "none" || /^matrix\(1, 0, 0, 1, 0, -?1\)$/.test(shape.transform), "keep the existing 1px composer hover but never scale its text");
  results.push({ corners: shape });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await input.fill("减少动态效果");
  await page.waitForTimeout(120);
  const stoppedFrames = await page.locator(".composerAmbientGlowCanvas").getAttribute("data-drawn-frames");
  await page.waitForTimeout(250);
  assert.equal(await page.locator(".composerAmbientGlowCanvas").getAttribute("data-drawn-frames"), stoppedFrames);
  results.push("减少动态效果时停止流动");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await input.fill("测试渲染降级");
  await canvas.evaluate(element => element.getContext("webgl2").getExtension("WEBGL_lose_context").loseContext());
  await page.waitForTimeout(200);
  assert.equal(await page.locator(".composerAmbientGlowCanvas").getAttribute("data-renderer"), "fallback");
  assert.equal(await input.inputValue(), "测试渲染降级");
  results.push("WebGL上下文丢失后静态降级，编辑器仍可用");
  assert.deepEqual(errors, []);
  await fs.writeFile(`${evidence}/browser-results.json`, JSON.stringify({ results, errors, physicalIphoneTested: false }, null, 2));
  console.log(JSON.stringify({ evidence, results, errors }, null, 2));
} catch (error) {
  await fs.writeFile(`${evidence}/browser-failure.json`, JSON.stringify({ results, errors, failure: String(error) }, null, 2));
  throw error;
} finally { await context.close(); await browser.close(); }
